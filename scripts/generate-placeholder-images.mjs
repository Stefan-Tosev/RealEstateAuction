import { mkdir, copyFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

/*
 * Generates the demo catalogue's placeholder photographs.
 *
 * Every listed property must have images, and six of the seven demo lots
 * are invented properties — you cannot photograph a building that does
 * not exist, and dressing them with stock photos of real apartments
 * would present fabricated listings as genuine. So they get honest
 * abstract placeholders, rendered from the same gradient definitions v1
 * drew in CSS (css/styles.css, .lot-image-1 .. .lot-image-8).
 *
 * Real photography replaces these by dropping files in and updating the
 * seed — no code changes.
 *
 * Run: node scripts/generate-placeholder-images.mjs
 */

const OUT_ROOT = path.join(process.cwd(), "public", "media", "properties");
const WIDTH = 1600;
const HEIGHT = 1200;

// Transcribed from css/styles.css. [linearFrom, linearTo, radialCx, radialCy,
// radialInner, radialOuter] — the same two-layer construction as the CSS.
const GRADIENTS = {
  1: ["rgba(46,79,163,0.42)", "rgba(10,16,32,0.72)", "30%", "30%", "#1d2c55", "#0a1020"],
  2: ["rgba(100,134,216,0.30)", "rgba(10,16,32,0.74)", "70%", "30%", "#223c6b", "#0a1020"],
  3: ["rgba(46,79,163,0.30)", "rgba(10,16,32,0.72)", "40%", "60%", "#1a2748", "#0a1020"],
  4: ["rgba(22,38,79,0.60)", "rgba(10,16,32,0.76)", "60%", "40%", "#182444", "#0a1020"],
  5: ["rgba(100,134,216,0.26)", "rgba(10,16,32,0.72)", "35%", "45%", "#20305c", "#0a1020"],
  6: ["rgba(10,16,32,0.50)", "rgba(10,16,32,0.82)", "50%", "50%", "#141c33", "#070b17"],
  7: ["rgba(46,79,163,0.34)", "rgba(10,16,32,0.72)", "55%", "35%", "#1b2a50", "#0a1020"],
  8: ["rgba(100,134,216,0.34)", "rgba(10,16,32,0.70)", "45%", "40%", "#243560", "#0a1020"],
};

function svgFor(n, seedLabel) {
  const [linFrom, linTo, cx, cy, inner, outer] = GRADIENTS[n];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${WIDTH}" height="${HEIGHT}">
  <defs>
    <radialGradient id="r" cx="${cx}" cy="${cy}" r="75%">
      <stop offset="0%" stop-color="${inner}"/>
      <stop offset="100%" stop-color="${outer}"/>
    </radialGradient>
    <linearGradient id="l" x1="0%" y1="0%" x2="62%" y2="100%">
      <stop offset="0%" stop-color="${linFrom}"/>
      <stop offset="100%" stop-color="${linTo}"/>
    </linearGradient>
  </defs>
  <rect width="100%" height="100%" fill="url(#r)"/>
  <rect width="100%" height="100%" fill="url(#l)"/>
  <text x="50%" y="50%" text-anchor="middle" dominant-baseline="middle"
        font-family="monospace" font-size="34" letter-spacing="6"
        fill="rgba(236,239,247,0.34)">${seedLabel}</text>
</svg>`;
}

/*
 * Each placeholder is labelled with its lot reference. Anyone looking at
 * a screenshot can tell instantly that it is not photography — which is
 * the point. A placeholder that tries to pass for a real photo is the
 * one that eventually ships to production unnoticed.
 */
const TARGETS = [
  { slug: "dvustaen-karshiyaka-plovdiv", real: "assets/images/dvustaen-ribbon.jpg", files: ["01.jpg"] },
  { slug: "tristaen-lozenets-sofia", gradient: 2, label: "LOT 012", files: ["01.jpg", "02.jpg"] },
  { slug: "kashta-boyana-sofia", gradient: 3, label: "LOT 013", files: ["01.jpg"] },
  { slug: "mezonet-more-varna", gradient: 4, label: "LOT 014", files: ["01.jpg"] },
  { slug: "kashta-stariya-grad-plovdiv", gradient: 5, label: "LOT 015", files: ["01.jpg", "02.jpg"] },
  { slug: "targovsko-vitosha-sofia", gradient: 6, label: "LOT 016", files: ["01.jpg"] },
  { slug: "partsel-pirin-bansko", gradient: 7, label: "LOT 017", files: ["01.jpg"] },
];

async function main() {
  for (const target of TARGETS) {
    const dir = path.join(OUT_ROOT, target.slug);
    await mkdir(dir, { recursive: true });

    if (target.real) {
      await copyFile(path.join(process.cwd(), target.real), path.join(dir, target.files[0]));
      console.log(`copied  ${target.slug}/${target.files[0]}`);
      continue;
    }

    for (const [index, file] of target.files.entries()) {
      const label = target.files.length > 1 ? `${target.label} · ${index + 1}` : target.label;
      const svg = svgFor(target.gradient, label);
      await sharp(Buffer.from(svg)).jpeg({ quality: 82 }).toFile(path.join(dir, file));
      console.log(`rendered ${target.slug}/${file}`);
    }
  }

  await writeFile(
    path.join(OUT_ROOT, "README.md"),
    [
      "# Demo media",
      "",
      "Generated by `scripts/generate-placeholder-images.mjs`.",
      "",
      "These are **placeholders**, not photographs of real properties — six of the",
      "seven demo lots are invented, so there is nothing to photograph. They are",
      "rendered from the v1 prototype's CSS gradients and labelled with their lot",
      "reference so they can never be mistaken for real listings.",
      "",
      "Replace by dropping real files in and updating `prisma/seeds/listings.ts`",
      "(filenames, alt text, and intrinsic width/height). No code changes needed.",
      "",
    ].join("\n"),
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
